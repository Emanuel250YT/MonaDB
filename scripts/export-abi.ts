/**
 * Copy the compiled MonaDB ABI into the SDK and the node, and regenerate
 * sdk/src/deployments.ts from deployments/monad-*.json.
 *
 *   npx hardhat compile && npm run export-abi
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const artifact = JSON.parse(fs.readFileSync(path.join(root, 'artifacts/contracts/MonaDB.sol/MonaDB.json'), 'utf8'));
const abi = JSON.stringify(artifact.abi, null, 2) + '\n';

for (const target of ['sdk/src/abi/MonaDB.json']) {
  fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  fs.writeFileSync(path.join(root, target), abi);
  console.log(`ABI → ${target}`);
}

// Public deployments (localnet stays out: its address changes every run)
const dir = path.join(root, 'deployments');
const entries: string[] = [];
for (const file of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  const match = /^monad-(testnet|mainnet)\.json$/.exec(file);
  if (!match) continue;
  const d = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  entries.push(
    `  ${match[1]}: ${JSON.stringify({
      network: d.network,
      chainId: d.chainId,
      rpcUrl: d.rpcUrl,
      contract: d.contract,
      deployBlock: d.deployBlock,
      ...(d.nodes?.length ? { nodes: d.nodes } : {}),
    })},`,
  );
}
fs.writeFileSync(
  path.join(root, 'sdk/src/deployments.ts'),
  `// Generated by scripts/export-abi.ts from deployments/monad-*.json — do not edit.\n` +
    `import type { MonaDBDeployment } from './client';\n\n` +
    `export const DEPLOYMENTS: Record<string, MonaDBDeployment> = {\n${entries.join('\n')}${entries.length ? '\n' : ''}};\n`,
);
console.log(`deployments.ts: ${entries.length} network(s)`);
